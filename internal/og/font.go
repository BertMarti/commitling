// TextWidth is the width in pixels of s drawn at the given scale.
func TextWidth(s string, scale int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return (n*advance - 1) * scale
}

// glyph returns the 9 rows of r (a '?' if the font lacks it), padding the
// 7-row glyphs with two empty rows.
func glyph(r rune) [glyphH]string {
	g, ok := font[r]
	if !ok {
		g = font['?']
	}
	var out [glyphH]string
	for i := range out {
		if i < len(g) {
			out[i] = g[i]
		} else {
			out[i] = "....."
		}
	}
	return out
}
